// ------------------------------------------------------------------
// 通用小工具
// ------------------------------------------------------------------
inline uint32_t rotl32(uint32_t x, int n) { return (x << n) | (x >> (32 - n)); }
inline uint32_t rotr32(uint32_t x, int n) { return (x >> n) | (x << (32 - n)); }

inline void appendBE32(std::string& out, uint32_t v) {
    out.push_back(static_cast<char>((v >> 24) & 0xFF));
    out.push_back(static_cast<char>((v >> 16) & 0xFF));
    out.push_back(static_cast<char>((v >> 8) & 0xFF));
    out.push_back(static_cast<char>(v & 0xFF));
}

inline void appendBE64(std::string& out, uint64_t v) {
    for (int i = 7; i >= 0; --i) out.push_back(static_cast<char>((v >> (i * 8)) & 0xFF));
}

inline std::string hexEncode(const std::string& raw) {
    static const char* kHex = "0123456789abcdef";
    std::string out;
    out.reserve(raw.size() * 2);
    for (unsigned char c : raw) {
        out.push_back(kHex[c >> 4]);
        out.push_back(kHex[c & 0x0F]);
    }
    return out;
}

// 按 64 字节块做 padding（SHA1/SHA256 一样，只是末尾长度字段位数相同、字节序相同）
std::string padMessage(const std::string& msg) {
    const uint64_t bitLen = static_cast<uint64_t>(msg.size()) * 8;
    std::string out = msg;
    out.push_back(static_cast<char>(0x80));
    while (out.size() % 64 != 56) out.push_back(static_cast<char>(0x00));
    appendBE64(out, bitLen);
    return out;
}

